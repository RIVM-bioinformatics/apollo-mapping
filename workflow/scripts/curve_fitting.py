#!/usr/bin/env python3
"""Determine genomic coverage and variant quality filtering thresholds via distribution fitting.

Reads per-base coverage depths from a BigWig file and variant quality (QUAL) scores
from a VCF file, identifies the primary distribution peak while accounting for low-value
noise and peak assumptions, delimits the distribution around the peak, fits candidate
SciPy probability distributions ranked by AIC, and exports percent-point function (PPF)
quantile thresholds to a YAML configuration file.

Args (CLI):
    -v, --vcf_file: Path to the input VCF file.
    -b, --bigwig_file: Path to the input BigWig file.
    -o, --output: Path to the output YAML file.
    --p_values: Optional comma-separated probabilities for PPF evaluation.
    --min_summated_counts_cov: Minimum required observations for coverage curve fitting.
    --min_summated_counts_score: Minimum required observations for score curve fitting.

Raises:
    ValueError: If no local noise valley is found, coverage falls below the minimum
        threshold, an unsupported model name is given, or distribution parameters have
        an unexpected count.
    NotImplementedError: If quality-of-fit calculation is requested for an unsupported
        SciPy distribution.
    InsufficientDataPoints: If delimited observations are below the required minimum
        count for curve fitting.

Returns:
    None: Writes selected models and PPF threshold tables to the specified YAML file.

Authors: Sofie Hofman & Ate van der Burgt
"""


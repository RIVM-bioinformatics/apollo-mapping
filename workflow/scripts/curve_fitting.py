def parse_p_values(p_str: str) -> list[float]:
    """Convert a comma-separated string of probabilities into a list of floats."""
    try:
        # Split by comma and convert each element to a float
        p_list = [float(p.strip()) for p in p_str.split(",")]

        # Validate that all probabilities are strictly between 0 and 1
        if any(p <= 0 or p >= 1 for p in p_list):
            raise argparse.ArgumentTypeError(
                "All p-values must be strictly between 0 and 1 (exclusive)."
            )
        return p_list
    except ValueError:
        raise argparse.ArgumentTypeError(
            "p-values must be a comma-separated list of numerical values."
        )

def count_variant_scores(vcf_file:str) -> dict:
    """Count the amount of times a quality score value occurs in a .vcf file

    Args:
        vcf_file (Path): path to .vcf file generated by Freebayes

    Returns:
        dict: dictonary with score values as keys and the amount of times 
        they occur in the data as values, e.g. {score:occurance}
    """
    logging.info(f"Counting quality scores in {vcf_file}...")  
    score_counter = Counter()

    with open(vcf_file, "r") as file_open:
        for line in file_open:
            if line.startswith("#"):
                continue
            
            columns = line.strip().split("\t")
            if len(columns) > 5:
                qual = columns[5]

                if qual != '.':
                    score = int(round(float(qual))) # bin scores to nearest integer
                    score_counter[score] += 1

    # sort values
    score_counts = dict(sorted(score_counter.items()))

    return score_counts


def count_coverage_per_base(file:str) -> dict:
    """Counts the amount of times a coverage values appear in the data

    Args:
        file (str): location to a bigwig file

    Returns:
        dict: dictonary with coverage values as keys and the amount of times 
        they occur in the data as values, e.g. {coverage:occurance}
    """
    logging.info(f"Counting coverage values in {file}...")
    bw = pyBigWig.open(file)

    #count coverage instances per base pair
    all_values = Counter()
    for chromosome, length in bw.chroms().items():
        values = np.array(bw.values(chromosome, 0, length))
        int_values = np.round(values).astype(int)
        all_values.update(int_values.tolist())
    bw.close()

    # sort values
    coverage_counts = dict(sorted(all_values.items()))

    return coverage_counts

def get_extrema_threshold(data: np.ndarray, bins: int = 100, smooth_window: int = 5) -> float:
    """Estimate a dynamic threshold separating low-value noise from the main distribution peak.

    Constructs a smoothed histogram density profile of the input data, detects local
    minima (valleys), and selects the first positive local minimum closest to zero
    (falling back to the absolute minimum closest to zero if none are positive).

    Args:
        data (np.ndarray): 1D array of numerical observations (e.g., coverage depths or quality scores).
        bins (int, optional): Number of equal-width bins used to compute the histogram density. Defaults to 100.
        smooth_window (int, optional): Moving-average kernel size used to smooth histogram counts and suppress spurious local minima. Defaults to 5.

    Raises:
        ValueError: If no local minima are detected in the smoothed histogram density profile.

    Returns:
        float: The bin-center value of the local minimum separating the near-zero noise spike from the primary distribution.
    """
    # 1. Generate histogram density profile
    counts, bin_edges = np.histogram(data, bins=bins, density=True)
    bin_centers = (bin_edges[:-1] + bin_edges[1:]) / 2

    # Smooth the counts to avoid microscopic local minima from random sampling
    smoothed_counts = np.convolve(counts, np.ones(smooth_window)/smooth_window, mode='same')

    # 2. Find all local minima indices 
    # np.less finds indices where the value is lower than its neighbors
    minima_indices = signal.argrelextrema(smoothed_counts, np.less)[0]

    if len(minima_indices) == 0:
        raise ValueError("No distinct noise valley found. Try increasing 'bins' or decreasing 'smooth_window'.")

    # 3. Find the minimum closest to 0
    minima_values = bin_centers[minima_indices]
    positive_minima = minima_values[minima_values > 0]

    if len(positive_minima) == 0:
        # Fallback if no positive minimum found: take the absolute closest minimum to zero
        dynamic_threshold = np.abs(minima_values[np.argmin(np.abs(minima_values))])
    else:
        # The very first minimum after 0 is where the noise spike terminates
        dynamic_threshold = positive_minima[0]

    return dynamic_threshold

def check_peak_assumptions(highest_peak, counts_peaks: dict, mu: float, stdv: float, data_type: str) -> None:

    # check lower limits of data coverage
    if data_type == "coverage":
        coverage_threshold = 7
        if highest_peak.value < coverage_threshold:
            raise ValueError(f"Data coverage is below the minimum threshold {coverage_threshold}. Please check the input data.")
        elif coverage_threshold <= highest_peak.value < 12:
            logging.warning(f"Data coverage is very low ({highest_peak.value}x). Please check the input data.")

    #make bins around the highest peak
    step = max(1, int(round(0.25 * stdv)))
    half_step = step // 2
    start = highest_peak.value - half_step - (2* step)

    bins = [
        list(range(start,              start + step)),       # Bin Index 0
        list(range(start + step,       start + 2 * step)),   # Bin Index 1
        list(range(start + 2 * step,   start + 3 * step)),   # Bin Index 2 (Center)
        list(range(start + 3 * step,   start + 4 * step)),   # Bin Index 3
        list(range(start + 4 * step,   start + 5 * step))    # Bin Index 4
    ] 
    
    #check if summated count B{-2}<B{-1}<B>B{+1}>{B+2}
    bin_counts = []
    for bin in bins:
        current_bin_count = 0
        for bin_value in bin:
            current_bin_count += counts_peaks.get(bin_value, 0)
        bin_counts.append(current_bin_count)

    # check if assumption of B{-2}<B{-1}<B>B{+1}>{B+2} is violated
    bin_assumption = (bin_counts[0] <= bin_counts[1] <= bin_counts[2] and 
                        bin_counts[2] >= bin_counts[3] >= bin_counts[4])
    if not bin_assumption:
        logging.warning(
            f"""The assumption of B{{-2}}<B{{-1}}<B>B{{+1}}>B{{+2}} is violated for the highes peak {highest_peak.value}: {data_type}.
                    Current bin values are:
                    B{{-2}}:
                        coverage range: {bins[0]}
                        summated count: {bin_counts[0]}
                    B{{-1}}:
                        coverage range: {bins[1]}
                        summated count: {bin_counts[1]}
                    B:
                        coverage range: {bins[2]}
                        summated count: {bin_counts[2]}
                    B{{+1}}:
                        coverage range: {bins[3]}
                        summated count: {bin_counts[3]}
                    B{{+2}}:
                        coverage range: {bins[4]}
                        summated count: {bin_counts[4]}
            """
            )
            
    # check if highest peak in range mu +/- 2*stdv
    if not (mu - 2 * stdv <= highest_peak.value <= mu + 2 * stdv):
        logging.warning(
            f"""The highest peak {highest_peak.value} is outside the expected range of mu +/- 2*stdv for {data_type}.
            Highest peak: {highest_peak.value}
            Expected range: {mu - 2 * stdv} - {mu + 2 * stdv}
            """
            )

def determine_highest_peak(counts:dict, data_type:str, prior_mu=None, prior_stdv=None) -> HighestPeak:
    """Determines the highest peak in the count distribution

    Args: 
        counts (dict): dictonary with score or count values as keys and the amount of times 
        they occur in the data as values, e.g. {coverage:occurance}
        data_type (str): data_type of data -> currently only supports coverage counts and Freebayes score counts
        prior_mu (float): estimated mu from simulating a genome with same coverage and depth as sample.
        Default is set to None.
        prior_stdv (float): estimated stdev from simulating a genome with same coverage and depth as sample.
        Default is set to None.

    Returns:
        tuple: tuple containing the coordinates of the highest peak

    """
    logging.info(f"Determining highest peak for {data_type}...")
    
    counts_peaks = counts.copy()

    if data_type == "coverage":
        #filter out 2x coverage -> poor quality NGS run or big ANI drop causes huge spike at 1x/2x
        for key in list(counts.keys()):
            if key <= 2:
                del counts_peaks[key]
    elif data_type == "score":
        #make bins for score data to counteract wide spread of values
        bin_width = 5
        binned_peaks = {}
        for score, count in counts.items():
            bin_start = int((score // bin_width) * bin_width)
            binned_peaks[bin_start] = binned_peaks.get(bin_start, 0) + count
        counts_peaks = binned_peaks

        #filter out 0 score
        counts_peaks.pop(0, None)

    #remove upper 5% of data
    data = []
    for value, count in counts_peaks.items():
        data.extend([value] * count)
    data = np.array(data)
    cutoff = np.percentile(data, 95)
    data = data[data <= cutoff]

    #calculate stdv and mu if not given
    if prior_stdv == None and prior_mu == None:
        mu, stdv = stats.norm.fit(data)
    else:
        mu = prior_mu
        stdv = prior_stdv

    #determine highest peak
    max_value = int(max(counts_peaks, key=counts_peaks.get))
    max_count = counts_peaks[max_value]
    highest_peak = HighestPeak(max_value, max_count)
    
    # check if highest peak is right of local minimum
    dynamic_threshold = get_extrema_threshold(data)
    print(f"Dynamic threshold for {data_type}: {dynamic_threshold}")
    if max_value <= dynamic_threshold:
        logging.warning(
            f"""The highest peak is left of the local minimum.
            Highest peak: {max_value}
            Local minimum: {dynamic_threshold}
            Determining highest peak based on local minimum instead of global maximum for {data_type}.
            """
            )
        
        # determine highest peak right of the local minimum
        secondary_max_count, secondary_max_value = max(((count, value) for value, count in counts_peaks.items() if value > dynamic_threshold), default=(None, None))
        if secondary_max_value is not None:
            highest_peak = HighestPeak(secondary_max_value, secondary_max_count)
            max_value = secondary_max_value
            max_count = secondary_max_count
        else:
            logging.warning(
                f"""No peak found right of the local minimum for {data_type}.
                Highest peak remains as global maximum: {max_value}
                """
                )
    
    # check if highest peak is actually highest peak and within mu +/- 2*stdv
    check_peak_assumptions(highest_peak, counts_peaks, mu, stdv, data_type)
        
    #log output values in table
    log_lines = [
        "\n" + "="*69,
        f"   HIGHEST PEAK METRICS FOR {data_type.upper()}",
        "="*69,
        f"{'Mu (Mean)':<15} | {'Stdv':<15} | {'Highest Peak':<15} | {'Highest Count':<15}",
        "-"*69,
        f"{float(mu):<15.2f} | {float(stdv):<15.2f} | {int(max_value):<15} | {int(max_count):<15}",
        "="*69
    ]
    logging.info("\n".join(log_lines))
     
    return highest_peak
        
    
def make_delimited_dataframe(counts: dict, highest_peak: HighestPeak) -> dict:
    """Delimit dataframe to a range around the highest peak to exclude outliers and make it more suitable for curve fitting

    Args:
        coverage_counts (dict): dictonary with coverage values as keys and the amount of times 
        they occur in the data as values, e.g. {coverage:occurance}
        highest_peak (tuple): tuple containing the coverage value of the highest peak and its count, e.g. (coverage, count)
    Returns:
        dict: dictonary with coverage values as keys and the amount of times they occur in the data as values, 
        e.g. {coverage:occurance}, but only for coverage values within a certain range around the highest peak
    """
    logging.info(f"Delimiting dataframe to a range around the highest peak...")
            
    # filter out coverage 0
    counts_min_max = counts.copy()
    for key in list(counts_min_max.keys()):
        if key <= 0:
            del counts_min_max[key]

    # determine minimum value
    below_peak_counts = {coverage: count for coverage, count in counts_min_max.items() if coverage<=highest_peak.value}
    mincount = min(below_peak_counts.values())
    lower_limit = [k for k, v in below_peak_counts.items() if v == mincount][0] # if there are multiple minimum values with same count the first occurence is chosen

    # determine maximum value
    upper_limit = highest_peak.value + (highest_peak.value - lower_limit)   #mirrors the minimum value so assumes a normal distribution

    # delimit dataframe to minimum and maximum values
    filtered_counts = {}
    for key, value in counts.items():
        if lower_limit <= key <= upper_limit:
            filtered_counts[key] = value

    return filtered_counts

def calculate_quality_of_fit(distribution, data, params) -> float:
    """ Returns a fractional (1.0 - 0.0) quality of fit how the assumed scipy.stats distribution fits the observation
        Supported distributions: norm, gennorm, hypsecant, t"""
    
    logging.info(f"Calculating quality of fit for {distribution.name}...")

    #check distribution input
    supported_distributions = ('norm', 'gennorm', 'hypsecant', 't')
    if distribution.name not in supported_distributions:
        raise NotImplementedError(f"calculate_qualty_of_fit: {distribution.name}")

    # make binning structure
    counted = Counter(data)
    data_min = min(counted)
    data_max = max(counted)
    n_bins = data_max - data_min + 1
    histo, bin_edges = np.histogram(data, bins=n_bins)

    # unpack scipy params
    extra_params = {"gennorm": "beta", "t": "df"}
    if len(params) == 3:
        shape_param, mu, stdv = params
        extra_kwargs = {extra_params[distribution.name]: shape_param}
    elif len(params) == 2:
        mu, stdv = params
        extra_kwargs = {}
    else:
        raise ValueError(f"Unexpected amount of parameters: {len(params)}")

    # calculate quality of fit metric 
    cdf = distribution.cdf(bin_edges, loc=mu, scale=stdv, **extra_kwargs)
    expected_values = len(data) * np.diff(cdf)
    abs_diff = np.abs(histo - expected_values)
    qof = float(1.0 - (np.sum(abs_diff) / len(data)))

    return qof

def log_fitting_results(results: list, data_type:str) -> None:
    """
    Cleans up distribution fitting results and logs them with accurate headers.
    """
    log_lines = [
        "\n" + "="*85,
        f"   DISTRIBUTION FITTING SUMMARY FOR {data_type.upper()}",
        "="*85,
        f"{'Distribution Name':<22} | {'AIC':<15} | {'QoF':<12} | {'Parameters':<30}",
        "-"*85
    ]
    
    # Unpack results and format them for logging
    for name, aic, _scipy_obj, params, qof in results:
        clean_params = tuple(round(float(p), 4) for p in params)
        
        line = (
            f"{name:<22} | "
            f"{aic:<15.2f} | "
            f"{qof:<12.4f} | "
            f"{clean_params}"
        )
        log_lines.append(line)
        
    log_lines.append("="*85)
    logging.info("\n".join(log_lines))

def curve_fitting(filtered_counts, data_type, min_summated_counts:int, prior_mu=None, prior_stdv=None):
    """Fit candidate probability distributions to count data and select the best model via AIC.

    Evaluates normal, generalized normal, and hyperbolic secant distributions using
    maximum likelihood estimation, ranking them by Akaike Information Criterion (AIC).
    If the best-fitting model's quality of fit (QoF) falls below 0.85, a Student's t
    distribution is also fitted and evaluated.

    Args:
        filtered_counts (dict[int, int]): Delimited mapping of observed values (e.g., coverage depth or quality score) to their occurrence counts.
        data_type (str): Label identifying the metric being fitted (e.g., 'coverage' or 'score').
        min_summated_counts (int): Minimum total number of observations required to proceed with curve fitting.
        prior_mu (float | None, optional): Prior mean estimate (currently unused). Defaults to None.
        prior_stdv (float | None, optional): Prior standard deviation estimate (currently unused). Defaults to None.

    Raises:
        InsufficientDataPoints: If the total number of expanded observations is less than `min_summated_counts`.

    Returns:
        tuple[BestFit, list[tuple]]: A tuple containing:
            - best_fit (BestFit): Dataclass encapsulating the lowest-AIC model, its parameters, and quality of fit.
            - results (list[tuple]): All evaluated models sorted by ascending AIC as `(name, aic, dist, params, qof)` tuples.
    """
    logging.info(f"Fitting distributions to {data_type} data...")

    # Build data array from rounts
    data = []
    for value, count in filtered_counts.items():
        data.extend([value] * count)

    # CHECKPOINT: Check if there is enough data available for curve fitting
    if len(data) < min_summated_counts:
        raise InsufficientDataPoints(
            f"Insufficient data points ({len(data)}) for curve fitting with {data_type} values."
            f"Required minimum: {min_summated_counts}"
        )

    # 
    results = []

    initial_dist_map = {
        "normal": stats.norm,
        "generalized_normal": stats.gennorm,
        "hyperbolic_secant": stats.hypsecant
    }

    optional_dist_map = {
        "student_t": stats.t
    }
    
    for name, dist in initial_dist_map.items():
        logging.info(f"Fitting {name} distribution...")
        params = dist.fit(data)
        log_likelihood = np.sum(dist.logpdf(data, *params))
        aic = float(2 * len(params) - 2 * log_likelihood)
        qof = calculate_quality_of_fit(dist, data, params)
        results.append((name, aic, dist, params, qof))

    # sort by AIC value to determine best fitting model
    results.sort(key=lambda x: x[1]) 
    best_fit = BestFit(*results[0])  # Unpack the best fitting model into the BestFit class

    # run optional models if best fitting model qof < 0.85
    # TO DO: determine threshold
    if best_fit.qof < 0.85:
        for name, dist in optional_dist_map.items():
            logging.info(f"Fitting optional distribution {name}...")
            params = dist.fit(data)
            log_likelihood = np.sum(dist.logpdf(data, *params))
            aic = float(2 * len(params) - 2 * log_likelihood)
            qof = calculate_quality_of_fit(dist, data, params)
            results.append((name, aic, dist, params, qof))
        
        results.sort(key=lambda x: x[1]) 
        best_fit = BestFit(*results[0])

    # log the fitting results
    log_fitting_results(results, data_type)

    return best_fit, results

def plot_fitting_results(results: list[tuple], counts: dict[int, int], filtered_counts: dict[int, int], 
                         data_type: str, output_html: Union[str, Path, None] = None,) -> go.Figure | None:
    """Plot observed count histograms as bars with fitted probability density curves overlaid.

    Args:
        results (list[tuple]): Evaluated models from `curve_fitting` as `(name, aic, dist, params, qof)` tuples.
        counts (dict[int, int]): Full unfiltered mapping of observed values to occurrence counts.
        filtered_counts (dict[int, int]): Delimited mapping of values used for distribution fitting.
        data_type (str): Metric label ('coverage' or 'score') used for axis labels and title.
        output_html (str | Path | None, optional): Optional file path to save the interactive Plotly figure as HTML.

    Returns:
        go.Figure | None: The generated Plotly Figure object, or None if `filtered_counts` is empty.

    """
    logging.info(f"Plotting fitting results for {data_type}...")

    total_counts = sum(filtered_counts.values())
    if total_counts == 0:
        logging.warning(f"No filtered data available to plot distributions for {data_type}.")
        return None

    raw_keys = list(counts.keys())
    raw_values = list(counts.values())

    filtered_keys = list(filtered_counts.keys())
    filtered_values = list(filtered_counts.values())

    fig = go.Figure()

    # 1. Raw counts (background reference)
    fig.add_trace(
        go.Bar(
            x=raw_keys,
            y=raw_values,
            name="Raw Counts (Unfiltered)",
            marker_color="rgba(169, 169, 169, 0.35)",
            hovertemplate="Value: %{x}<br>Count: %{y}<extra></extra>",
        )
    )

    # 2. Delimited counts used for fitting (foreground bars)
    fig.add_trace(
        go.Bar(
            x=filtered_keys,
            y=filtered_values,
            name="Delimited Counts (Fitted)",
            marker_color="rgba(100, 149, 237, 0.75)",
            hovertemplate="Value: %{x}<br>Count: %{y}<extra></extra>",
        )
    )

    # 3. Fitted probability density curves scaled to discrete integer bin counts (bin_width = 1)
    x_min, x_max = min(filtered_keys), max(filtered_keys)
    x_span = max(1, x_max - x_min)
    pad = max(2, int(round(0.1 * x_span)))

    plot_x_min = max(0, x_min - pad)
    plot_x_max = x_max + pad

    x = np.linspace(x_min, x_max, 500)

    for i, (name, aic, distribution, params, qof) in enumerate(results):
        y_scaled = distribution.pdf(x, *params) * total_counts
        is_best = i == 0

        fig.add_trace(
            go.Scatter(
                x=x,
                y=y_scaled,
                mode="lines",
                name=f"{name} (AIC: {aic:.1f}, QoF: {qof:.3f})",
                line=dict(width=3 if is_best else 2, dash="solid" if is_best else "dash"),
            )
        )

    xaxis_label = "Quality Score" if data_type == "score" else "Coverage Depth"
    fig.update_layout(
        title=f"Genomic {data_type.capitalize()} Distribution & Model Fitting",
        xaxis_title=xaxis_label,
        yaxis_title="Summated Count",
        xaxis=dict(range=[plot_x_min, plot_x_max]),
        barmode="overlay",
        template="plotly_white",
        legend=dict(yanchor="top", y=0.99, xanchor="right", x=0.99),
        hovermode="x unified",
    )

    if output_html is not None:
        out_path = Path(output_html)
        out_path.parent.mkdir(parents=True, exist_ok=True)
        fig.write_html(out_path)
        logging.info(f"Saved {data_type} fit plot to {out_path}")
    else:
        fig.show()

    return fig

def generate_ppf_table(
    best_fit: BestFit,
    data_type: str,
    p_values: Union[np.ndarray, List[float], None] = None,
    num_digits: Union[int, None] = 0,
) -> tuple[str, dict]:
    """Generate a PPF threshold mapping for the best-fitting SciPy statistical model.

    Args:
        best_fit (BestFit): Dataclass containing the best fitting distribution and parameters.
        data_type (str): Type of data being processed ('coverage' or 'score').
        p_values (list[float] | np.ndarray | None): Probabilities to evaluate. Defaults to PPF_TABLE_DEFAULTS.
        num_digits (int | None): Decimal places to round thresholds (0 returns int, None disables rounding).

    Returns:
        tuple[str, dict]: The distribution name and a dictionary mapping {p_value: threshold}.
    """
    logging.info(f"Determining filter values for {data_type} using {best_fit.name}...")

    p_values = p_values if p_values is not None else PPF_TABLE_DEFAULTS
    params = tuple(map(float, best_fit.params))

    # Retrieve scipy.stats model (uses the object stored on BestFit, or falls back to name lookup)
    if hasattr(best_fit.distribution, "ppf"):
        model = best_fit.distribution
    else:
        try:
            model = getattr(stats, best_fit.distribution)
        except AttributeError as e:
            raise ValueError(
                f"Model '{best_fit.distribution}' is not a supported scipy.stats model."
            ) from e

    def _round(value: float) -> Union[int, float]:
        if np.isnan(value):
            return float("nan")
        if num_digits is None:
            return float(value)
        elif num_digits == 0:
            return int(round(value))
        else:
            return round(float(value), num_digits)

    # Guard against zero-variance edge cases (e.g., stdv <= 0)
    if len(params) >= 2 and params[-1] <= 0:
        loc = _round(params[-2])
        ppf_dict = {float(p): loc for p in p_values}
    else:
        data = [(float(p), _round(model.ppf(p, *params))) for p in p_values]
        df = pd.DataFrame(data, columns=("p", "threshold"))
        ppf_dict = dict(df.itertuples(index=False, name=None))

    logging.info(f"Determined filter values for {data_type}: {ppf_dict}")
    return best_fit.name, ppf_dict


def write_filter_values_to_file(
    output_path: Union[str, Path],
    filter_values_coverage: tuple[str, dict],
    filter_values_score: tuple[str, dict],
) -> None:
    """Write model names and PPF threshold tables for coverage and quality score to YAML."""
    logging.info(f"Writing filter values to {output_path}...")

    model_cov, ppf_table_cov = filter_values_coverage
    model_score, ppf_table_score = filter_values_score

    data = {
        "coverage": {
            "model": model_cov,
            "ppf_table": ppf_table_cov,
        },
        "quality_score": {
            "model": model_score,
            "ppf_table": ppf_table_score,
        },
    }

    path = Path(output_path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w") as f:
        yaml.safe_dump(data, f, sort_keys=False)

